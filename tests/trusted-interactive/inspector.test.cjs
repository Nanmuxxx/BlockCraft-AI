const test = require('node:test')
const assert = require('node:assert/strict')
require('../custom-block/fixtures.cjs')
const fs = require('node:fs'), ts = require('typescript')
require.extensions['.tsx'] = (module, filename) => module._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.ReactJSX, esModuleInterop: true }, fileName: filename }).outputText, filename)
require.extensions['.css'] = () => {}
const React = require('react')
const { renderToStaticMarkup } = require('react-dom/server')
const { AppSpecInspector } = require('../../src/components/app-builder/AppSpecInspector.tsx')
const { initializeGeneratedProject } = require('../../src/components/ai-create/generateApp.ts')
const { createClubRegistrationExample } = require('../../src/model/appSpecExamples.ts')
const render = (snapshot, blockId) => renderToStaticMarkup(React.createElement(AppSpecInspector, { snapshot, blockId, runtime: {} }))
test('pomodoro details accurately declare no data binding and expose no CRUD editor', () => {
  const state = initializeGeneratedProject(require('./pomodoro.json'))
  const html = render(state, 'focus-timer')
  assert.match(html, /无需数据绑定/)
  assert.doesNotMatch(html, /绑定异常|新增字段|role="alert"/)
  assert.match(html, /番茄钟配置/)
})
test('CRUD details preserve valid entity and warn on missing or ambiguous binding', () => {
  const state = createClubRegistrationExample(), blockId = state.spec.blocks[0].id
  assert.doesNotMatch(render(state, blockId), /绑定异常|无需数据绑定/)
  const missing = structuredClone(state)
  missing.spec.relations = missing.spec.relations.filter(r => r.blockId !== blockId)
  assert.match(render(missing, blockId), /role="alert">绑定异常/)
  const ambiguous = structuredClone(state)
  ambiguous.spec.relations.push({ ...state.spec.relations.find(r => r.blockId === blockId), id: 'duplicate-test-binding' })
  assert.match(render(ambiguous, blockId), /role="alert">绑定异常/)
})
