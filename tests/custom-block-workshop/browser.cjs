// Real /ai-create entry and production Workshop. Only generation HTTP is mocked.
// All custom input is inert protocol metadata; its source must never execute.
const { chromium } = require('playwright')
const { expect } = require('playwright/test')
const assert = require('node:assert/strict')
const { mkdir, writeFile } = require('node:fs/promises')
const path = require('node:path')
const { realpathSync } = require('node:fs')
const { api, artifact, createClubRegistrationExample } = require('../custom-block/fixtures.cjs')
const root = path.resolve(__dirname, '../..')
const output = process.env.CUSTOM_WORKSHOP_QA_OUTPUT || '/tmp/blockcraft-custom-workshop-audit'
async function payload(id, source = artifact(), props = { durationSeconds: 600 }) {
  const versionDigest = await api.computeVersionDigest(source)
  return { instance: { id, definitionId: source.manifest.definitionId, versionDigest, props }, artifact: { versionDigest, artifact: source } }
}
async function run() {
  const { createServer } = await import('vite')
  const vite = await createServer({ root, server: { host: '127.0.0.1', port: 5198, strictPort: true, fs: { allow: [root, path.dirname(realpathSync(path.join(root, 'node_modules/react')))] } } })
  const report = { browser: 'Chromium', route: '/ai-create', generation: 'offline HTTP response, no paid API', cases: [], errors: [] }
  let browser
  try {
    await mkdir(output, { recursive: true }); await vite.listen()
    browser = await chromium.launch({ headless: true })
    for (const width of [1366, 390]) {
      const page = await browser.newPage({ viewport: { width, height: 900 }, isMobile: width === 390, hasTouch: width === 390 })
      page.on('pageerror', error => report.errors.push(error.message))
      const outbound = [], requests = []
      await page.route('**/*', async route => {
        const url = new URL(route.request().url())
        if (!['127.0.0.1', 'localhost'].includes(url.hostname)) { outbound.push(url.href); return route.abort() }
        if (url.pathname === '/api/ai/generate') { requests.push(url.pathname); return route.fulfill({ json: createClubRegistrationExample().spec }) }
        if (url.pathname.startsWith('/api/')) { requests.push(url.pathname); return route.abort() }
        return route.continue()
      })
      const b = page.getByRole('button', { name: 'B 模式 · 编辑积木', exact: true })
      const c = page.getByRole('button', { name: 'C 模式 · 运行应用', exact: true })
      const card = id => page.locator(`[data-block-key="${id}"]`)
      const inspector = page.getByRole('complementary', { name: '自定义积木属性', exact: true })
      const importer = page.locator('.custom-block-import')
      const importDraft = async value => {
        if (!await importer.evaluate(e => e.open)) await importer.locator('summary').click()
        await importer.getByLabel('积木制品 JSON').setInputFiles({ name: 'inert-artifact.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(value)) })
        await expect(importer.getByRole('button', { name: /确认(添加积木|替换版本)/ })).toBeEnabled()
      }
      const install = async value => {
        await importDraft(value)
        await importer.getByRole('button', { name: /确认(添加积木|替换版本)/ }).click()
        await expect(importer.getByRole('status')).toContainText('制品已校验并登记')
      }
      const source = artifact(); source.manifest.name = '惰性制品测试'
      const first = await payload('custom-1', source)
      await page.goto('http://127.0.0.1:5198/ai-create')
      await page.getByLabel('你想做什么软件？').fill('社团迎新报名，离线产品回归')
      await page.getByRole('button', { name: '生成应用', exact: true }).click()
      await expect(card('builtin:registration-form')).toBeVisible()
      assert.equal(await page.locator('[data-block-key]').count(), 3)
      await install(first)
      await expect(card('custom:custom-1')).toBeVisible()
      assert.equal(await page.locator('[data-block-key]').count(), 4)
      await card('custom:custom-1').click()
      await expect(inspector.getByLabel('durationSeconds', { exact: true })).toHaveValue('600')
      await expect(page.getByRole('textbox', { name: '给 Mochi 发消息' })).toBeDisabled()
      assert.equal(await page.locator('.mochi-ai').count(), 1)
      assert.equal(await page.locator('.logo').count(), 1)
      // Host Schema rejection preserves the committed props, not just HTML validity.
      await inspector.getByLabel('durationSeconds', { exact: true }).fill('0')
      await inspector.getByRole('button', { name: '保存参数', exact: true }).click()
      await expect(inspector.getByRole('alert')).toBeVisible()
      await inspector.getByRole('button', { name: '重新载入参数', exact: true }).click()
      await expect(inspector.getByLabel('durationSeconds', { exact: true })).toHaveValue('600')
      await inspector.getByLabel('durationSeconds', { exact: true }).fill('900')
      await inspector.getByRole('button', { name: '保存参数', exact: true }).click()
      await expect(inspector.getByRole('status')).toContainText('宿主校验并保存')
      // An unrelated builtin edit invalidates a custom draft on the SAME revision.
      await inspector.getByLabel('durationSeconds', { exact: true }).fill('950')
      await page.getByRole('button', { name: '一键整理', exact: true }).click()
      await expect(inspector.getByText('项目已变化；请重新载入参数后再保存。')).toBeVisible()
      await expect(inspector.getByRole('button', { name: '保存参数', exact: true })).toBeDisabled()
      await inspector.getByRole('button', { name: '重新载入参数', exact: true }).click()
      await expect(inspector.getByLabel('durationSeconds', { exact: true })).toHaveValue('900')
      const custom = card('custom:custom-1')
      await custom.scrollIntoViewIfNeeded()
      const before = await custom.evaluate(e => ({ left: e.style.left, top: e.style.top }))
      const box = await custom.boundingBox()
      if (width === 390) {
        const touch = await page.context().newCDPSession(page)
        await touch.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: box.x + 30, y: box.y + 30 }] })
        for (let step = 1; step <= 12; step++) await touch.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: box.x + 30 + 30 * step / 12, y: box.y + 30 + 70 * step / 12 }] })
        await touch.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
        await touch.detach()
      } else {
        await page.mouse.move(box.x + 30, box.y + 30); await page.mouse.down()
        await page.mouse.move(box.x + 60, box.y + 100, { steps: 12 }); await page.mouse.up()
      }
      await expect(page.locator('.block-canvas-feedback')).toContainText(/位置已更新|拼上了|整组积木已移动/)
      await expect.poll(() => custom.evaluate(e => `${e.style.left},${e.style.top}`)).not.toBe(`${before.left},${before.top}`)
      const moved = await custom.evaluate(e => `${e.style.left},${e.style.top}`)
      await c.click(); await b.click()
      assert.equal(await custom.evaluate(e => `${e.style.left},${e.style.top}`), moved, 'layout persists across modes')
      await custom.click()
      // Invalid digest rejected; existing view and editable props stay intact.
      const invalid = structuredClone(first); invalid.artifact.artifact.sources['src/Counter.tsx'] += ' tampered'
      await importDraft(invalid); await importer.getByRole('button', { name: '确认替换版本', exact: true }).click()
      await expect(importer.getByRole('status')).toContainText('DIGEST_MISMATCH')
      await expect(inspector.getByLabel('durationSeconds', { exact: true })).toHaveValue('900')
      // Confirming an import against an intervening layout write is rejected.
      await importDraft(await payload('custom-late', source))
      await page.getByRole('button', { name: '一键整理', exact: true }).click()
      await expect(inspector.getByRole('button', { name: '保存参数', exact: true })).toBeDisabled()
      await importer.getByRole('button', { name: '确认添加积木', exact: true }).click()
      await expect(importer.getByRole('status')).toContainText('REVISION_CONFLICT')
      assert.equal(await card('custom:custom-late').count(), 0)
      // New reference after the adapter mounted must be admitted and editable.
      const secondSource = artifact(); secondSource.manifest.definitionId = 'other-definition'; secondSource.manifest.name = '另一惰性制品'
      const second = await payload('custom-2', secondSource)
      await install(second); await card('custom:custom-2').click()
      await expect(inspector.getByRole('heading', { name: '另一惰性制品', exact: true })).toBeVisible()
      await expect(inspector.getByLabel('durationSeconds', { exact: true })).toHaveValue('600')
      // Same definition, new digest AND Schema: old fields and drafts disappear.
      const versionSource = structuredClone(source); versionSource.manifest.name = '惰性制品版本二'
      versionSource.manifest.propsSchema = { type: 'object', properties: { label: { type: 'string', minLength: 1, maxLength: 32 } }, required: ['label'], additionalProperties: false }
      const version = await payload('custom-1', versionSource, { label: '新版参数' })
      await install(version); await card('custom:custom-1').click()
      await expect(inspector.getByLabel('label', { exact: true })).toHaveValue('新版参数')
      assert.equal(await inspector.getByLabel('durationSeconds', { exact: true }).count(), 0)
      await inspector.getByLabel('label', { exact: true }).fill('已编辑版本二')
      await inspector.getByRole('button', { name: '保存参数', exact: true }).click()
      await expect(inspector.getByRole('status')).toContainText('宿主校验并保存')
      // Builtin Inspector is still the existing product component.
      await card('builtin:applicant-list').click()
      const builtinInspector = page.getByRole('complementary', { name: '积木属性', exact: true })
      await builtinInspector.getByLabel('字段名称', { exact: true }).fill('备注')
      await builtinInspector.getByRole('button', { name: '新增字段', exact: true }).click()
      await builtinInspector.getByRole('checkbox', { name: '展示 备注', exact: true }).check()
      await card('custom:custom-1').click()
      await expect(inspector.getByLabel('label', { exact: true })).toHaveValue('已编辑版本二')
      await page.evaluate(() => document.fonts.ready)
      assert.match(await page.locator('.logo__word').evaluate(e => getComputedStyle(e).fontFamily), /Pixelify Sans/)
      await importer.locator('summary').click()
      await page.screenshot({ path: path.join(output, `workshop-b-${width}.png`), fullPage: true })
      await c.click()
      const viewers = page.locator('[data-viewer-status]')
      assert.equal(await viewers.count(), 2)
      const viewer = page.locator('[data-instance-id="custom-1"]')
      await expect(viewer).toHaveAttribute('data-definition-id', version.instance.definitionId)
      await expect(viewer).toHaveAttribute('data-version-digest', version.instance.versionDigest)
      await expect(viewer).toHaveAttribute('data-viewer-status', 'unavailable')
      await expect(viewer.getByText('运行暂不可用', { exact: true })).toBeVisible()
      assert.equal(await page.locator('iframe').count(), 0)
      assert.equal(await page.locator('script[src*="Counter"]').count(), 0)
      assert.deepEqual(await page.locator('[data-render-key]').evaluateAll(es => es.map(e => e.dataset.renderKey)), ['builtin:registration-form', 'builtin:applicant-list', 'builtin:applicant-total', 'custom:custom-1', 'custom:custom-2'])
      for (const name of ['报名表', '报名名单', '报名人数']) assert.equal(await page.getByRole('region', { name, exact: true }).count(), 1, 'one render per builtin')
      const list = page.getByRole('region', { name: '报名名单', exact: true })
      const metric = page.getByRole('region', { name: '报名人数', exact: true }).locator('output')
      const form = page.getByRole('region', { name: '报名表', exact: true })
      await form.getByLabel('姓名', { exact: false }).fill('小张')
      await form.getByLabel('意向部门', { exact: false }).selectOption('技术部')
      await form.getByRole('button', { name: '提交', exact: true }).click()
      await expect(list.getByRole('cell', { name: '小张', exact: true })).toBeVisible()
      await expect(metric).toHaveText('1')
      await list.getByRole('button', { name: '编辑', exact: true }).click()
      await list.getByLabel('姓名', { exact: false }).fill('小李')
      await list.getByLabel('备注', { exact: true }).fill('与自定义积木共用 owner')
      await list.getByRole('button', { name: '保存修改', exact: true }).click()
      await expect(list.getByRole('cell', { name: '小李', exact: true })).toBeVisible()
      await b.click(); await custom.click()
      await inspector.getByRole('button', { name: '重新载入参数', exact: true }).click()
      await expect(inspector.getByLabel('label', { exact: true })).toHaveValue('已编辑版本二')
      await c.click()
      await expect(list.getByRole('cell', { name: '与自定义积木共用 owner', exact: true })).toBeVisible()
      await page.screenshot({ path: path.join(output, `workshop-c-${width}.png`), fullPage: true })
      await list.getByRole('button', { name: '删除', exact: true }).click()
      await expect(list.getByText('暂无记录', { exact: true })).toBeVisible()
      await expect(metric).toHaveText('0')
      await list.getByRole('button', { name: '新增记录', exact: true }).click()
      await list.getByLabel('姓名', { exact: false }).fill('列表新增')
      await list.getByLabel('意向部门', { exact: false }).selectOption('策划部')
      await list.getByRole('button', { name: '提交', exact: true }).click()
      await expect(metric).toHaveText('1')
      await expect(viewer).toHaveAttribute('data-version-digest', version.instance.versionDigest)
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `${width}px horizontal overflow`)
      assert.deepEqual(requests, ['/api/ai/generate'])
      assert.deepEqual(outbound, [])
      report.cases.push({ width, passed: true, customInstances: 2, builtinRenders: 3, dragInput: width === 390 ? 'Chromium touch events' : 'mouse', reference: version.instance, checks: ['real product route', 'mixed selection/drag/layout persistence', 'trusted props save/Schema rejection', 'stale custom draft', 'invalid digest atomic rejection', 'concurrent import rejects', 'new definition admission', 'same-definition version/Schema re-admission', 'builtin Inspector field editing', 'builtin form/list CRUD and live metric', 'B/C state retention', 'exact unavailable viewer', 'no iframe or generated module execution', 'Logo/Pixelify/Mochi', 'no horizontal overflow'], paidCalls: 0 })
      // Legacy home → clarification → Demo retains its original task state.
      await page.goto('http://127.0.0.1:5198/')
      await page.getByLabel('描述你想创造的软件').fill('学习管理 App')
      await page.getByRole('button', { name: '开始创造' }).click()
      await page.getByRole('heading', { name: '先确定最重要的功能' }).waitFor()
      await page.getByRole('group', { name: '选择优先关注的功能' }).getByRole('button').first().click()
      await page.getByRole('heading', { name: '我的学习助手' }).waitFor()
      await page.getByRole('button', { name: 'C 应用预览' }).click()
      await page.locator('#study-task-draft').fill('旧 Demo 集成回归任务')
      await page.getByRole('button', { name: '添加任务', exact: true }).click()
      await expect(page.getByText('旧 Demo 集成回归任务', { exact: true })).toBeVisible()
      await page.getByRole('button', { name: 'B 功能积木' }).click()
      await page.getByRole('button', { name: 'C 应用预览' }).click()
      await expect(page.getByText('旧 Demo 集成回归任务', { exact: true })).toBeVisible()
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
      await page.screenshot({ path: path.join(output, `legacy-demo-${width}.png`), fullPage: true })
      report.cases.at(-1).checks.push('legacy Home/clarification/Demo task roundtrip')
      await page.close()
    }
    assert.deepEqual(report.errors, [])
    await writeFile(path.join(output, 'report.json'), JSON.stringify(report, null, 2))
    console.log(JSON.stringify(report, null, 2))
  } finally { await browser?.close(); await vite.close() }
}
run().catch(error => { console.error(error); process.exitCode = 1 })
