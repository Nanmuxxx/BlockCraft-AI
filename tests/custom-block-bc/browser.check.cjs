// Offline real Chromium interaction. Requires Playwright provided by the host.
const { chromium } = require('playwright')
const { expect } = require('playwright/test')
const { createServer } = require('vite')
const assert = require('node:assert/strict')
const { mkdir, writeFile, mkdtemp } = require('node:fs/promises')
const { tmpdir } = require('node:os')
const { realpathSync } = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '../..')

async function run() {
  const evidence = process.env.CUSTOM_BLOCK_BC_EVIDENCE ? path.resolve(process.env.CUSTOM_BLOCK_BC_EVIDENCE) : await mkdtemp(path.join(tmpdir(), 'blockcraft-bc-'))
  const relativeEvidence = path.relative(root, evidence)
  assert.ok(path.isAbsolute(relativeEvidence) || relativeEvidence === '..' || relativeEvidence.startsWith(`..${path.sep}`), 'evidence must be outside the checkout; never overwrite tracked screenshots')
  const dependencyRoot = path.dirname(realpathSync(path.join(root, 'node_modules/react')))
  const vite = await createServer({ root, server: { host: '127.0.0.1', port: 5194, strictPort: true, fs: { allow: [root, dependencyRoot] } } })
  let browser
  try {
    await vite.listen()
    browser = await chromium.launch({ headless: true, ...(process.env.CUSTOM_BLOCK_BC_CHROMIUM ? { executablePath: process.env.CUSTOM_BLOCK_BC_CHROMIUM } : {}) })
    const results = [], externalRequests = [], errors = [], assetErrors = []
    await mkdir(evidence, { recursive: true })
    for (const viewport of [{ width: 1366, height: 900 }, { width: 390, height: 900 }]) {
      const context = await browser.newContext({ viewport, reducedMotion: 'reduce' })
      const page = await context.newPage()
      page.on('pageerror', error => errors.push(error.message))
      page.on('response', response => { if (response.status() >= 400) assetErrors.push(response.url()) })
      await page.route('**/*', route => {
        const url = new URL(route.request().url())
        if (url.origin !== 'http://127.0.0.1:5194') { externalRequests.push(url.href); return route.abort() }
        if (url.pathname.startsWith('/api/')) throw Error('Unexpected API call')
        return route.continue()
      })
      const snapshot = async () => JSON.parse(await page.getByTestId('snapshot').textContent())
      const card = page.locator('[data-block-key="custom:custom-1"]')
      const navigate = async () => { await page.goto('http://127.0.0.1:5194/tests/custom-block-bc/browser/'); await expect(card).toBeVisible() }
      await navigate()
      const initial = await snapshot()
      assert.equal(initial.revision, 0)
      const orderedKeys = initial.renderOrder.map(item => `${item.kind}:${item.id}`)
      assert.deepEqual(await page.locator('[data-block-key]').evaluateAll(nodes => nodes.map(node => node.getAttribute('data-block-key'))), orderedKeys)
      await card.click()
      await expect(card).toHaveAttribute('aria-pressed', 'true')
      const inspector = page.getByRole('complementary', { name: '自定义积木属性' })
      await expect(inspector.getByLabel('durationSeconds', { exact: true })).toHaveValue('600')
      const beforeDraft = await snapshot()
      await inspector.getByLabel('durationSeconds', { exact: true }).fill('900')
      assert.deepEqual(await snapshot(), beforeDraft, 'draft must not publish')
      await inspector.getByLabel('enabled', { exact: true }).selectOption('false')
      await inspector.getByLabel('mode', { exact: true }).selectOption('1')
      await inspector.getByLabel('speed', { exact: true }).selectOption('0')
      await inspector.getByLabel('approved', { exact: true }).selectOption('1')
      await inspector.getByLabel('启用 tuning', { exact: true }).check()
      await inspector.getByLabel('tuning.ratio', { exact: true }).fill('.25')
      await inspector.getByLabel('tuning.caption', { exact: true }).fill('手动配置')
      await inspector.getByRole('button', { name: '保存参数', exact: true }).click()
      await expect(inspector.getByRole('status')).toContainText('宿主校验并保存')
      let state = await snapshot()
      assert.equal(state.revision, 1)
      assert.deepEqual(state.custom.instances[0].props, { ...initial.custom.instances[0].props, durationSeconds: 900, enabled: false, mode: 'full', speed: .5, approved: true, tuning: { ratio: .25, caption: '手动配置' } })
      assert.deepEqual(state.custom.instances[1], initial.custom.instances[1])
      // Host validation, despite noValidate and programmatically bypassable input limits.
      await inspector.getByLabel('durationSeconds', { exact: true }).fill('1.5')
      await inspector.getByRole('button', { name: '保存参数', exact: true }).click()
      await expect(inspector.getByRole('alert')).toContainText('Invalid Schema integer')
      assert.equal((await snapshot()).revision, 1)
      await inspector.getByRole('button', { name: '重新载入参数' }).click()
      await page.getByRole('button', { name: '外部 revision（测试）', exact: true }).click()
      await expect(inspector.getByText('项目已变化；请重新载入参数后再保存。')).toBeVisible()
      await expect(inspector.getByRole('button', { name: '保存参数', exact: true })).toBeDisabled()
      await inspector.getByRole('button', { name: '重新载入参数' }).click()
      await inspector.getByLabel('启用 tuning', { exact: true }).uncheck()
      await inspector.getByRole('button', { name: '保存参数', exact: true }).click()
      await expect(inspector.getByRole('status')).toContainText('宿主校验并保存')
      assert.equal('tuning' in (await snapshot()).custom.instances[0].props, false)
      // Each physical pointer lifecycle goes through the original useSnapCanvas.
      await card.scrollIntoViewIfNeeded()
      let box = await card.boundingBox()
      let before = await snapshot()
      const dx = viewport.width > 600 ? 18 : 7
      await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
      await page.mouse.down(); await page.mouse.move(box.x + box.width / 2 + dx, box.y + box.height / 2, { steps: 6 }); await page.mouse.up()
      await expect(page.getByTestId('revision')).toHaveText(String(before.revision + 1))
      state = await snapshot()
      assert.notDeepEqual(state.custom.positions['custom-1'], before.custom.positions['custom-1'])
      assert.deepEqual(state.base, before.base); assert.deepEqual(state.custom.instances, before.custom.instances)
      // Cancel discards the drag and leaves persisted geometry/revision untouched.
      before = state
      box = await card.boundingBox()
      await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
      await page.mouse.down(); await page.mouse.move(box.x + box.width / 2 - dx, box.y + box.height / 2, { steps: 5 })
      await card.dispatchEvent('pointercancel', { pointerId: 1, pointerType: 'mouse', bubbles: true })
      await page.mouse.up()
      assert.deepEqual(await snapshot(), before)
      // Selection alone and switching between two instances never mutate config.
      await page.locator('[data-block-key="custom:custom-2"]').click()
      await expect(inspector.getByLabel('durationSeconds', { exact: true })).toHaveValue('600')
      await card.click()
      await expect(inspector.getByLabel('durationSeconds', { exact: true })).toHaveValue('900')
      assert.deepEqual(await snapshot(), before)
      await page.getByRole('button', { name: 'C 模式', exact: true }).click()
      assert.deepEqual(await page.locator('[data-render-key]').evaluateAll(nodes => nodes.map(node => node.getAttribute('data-render-key'))), orderedKeys)
      await expect(page.locator('[data-viewer-status="pending-build"]')).toHaveCount(2)
      assert.equal(await page.locator('iframe').count(), 0)
      await expect(page.locator('[data-instance-id="custom-1"]')).toHaveAttribute('data-version-digest', initial.custom.instances[0].versionDigest)
      await page.getByRole('button', { name: '后端不可用', exact: true }).click()
      await expect(page.locator('[data-viewer-status="unavailable"]')).toHaveCount(2)
      await page.getByRole('button', { name: '伪造 runnable（测试）', exact: true }).click()
      await expect(page.locator('[data-viewer-status="unavailable"]')).toHaveCount(2)
      await page.screenshot({ path: path.join(evidence, viewport.width > 600 ? 'desktop-c.png' : 'mobile-c.png'), fullPage: true })
      await navigate()
      assert.deepEqual(await snapshot(), before, 'full reload must restore authoritative v2 persisted state')
      await card.click()
      await expect(inspector.getByLabel('durationSeconds', { exact: true })).toHaveValue('900')
      await page.screenshot({ path: path.join(evidence, viewport.width > 600 ? 'desktop-b.png' : 'mobile-b.png'), fullPage: true })
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false)
      // Two-card scene tests actual mixed stack callbacks without unrelated obstacles.
      // A taller viewport keeps both endpoints visible; width remains desktop/mobile.
      await page.setViewportSize({ width: viewport.width, height: 1800 })
      await page.goto('http://127.0.0.1:5194/tests/custom-block-bc/browser/?drag-check=1')
      await expect(card).toBeVisible()
      const builtin = page.locator('[data-block-key^="builtin:"]')
      const dragTo = async (source, target) => {
        const origin = await source.boundingBox()
        await page.mouse.move(origin.x + origin.width / 2, origin.y + origin.height / 2)
        await page.mouse.down()
        await page.mouse.move(target.x, target.y, { steps: 12 })
        await page.mouse.up()
      }
      let geometry = await snapshot(), target = await builtin.boundingBox()
      await dragTo(card, { x: target.x + target.width / 2, y: target.y + target.height / 2 })
      await expect(page.getByRole('status').filter({ hasText: '挡住其他积木' })).toBeVisible()
      assert.deepEqual(await snapshot(), geometry, 'collision must not commit')
      target = await builtin.boundingBox()
      await dragTo(card, { x: target.x + target.width / 2, y: target.y + target.height / 2 + 208 })
      await expect(card).toHaveAttribute('aria-label', /已拼接 2 块/)
      await expect(page.getByTestId('revision')).toHaveText('1')
      geometry = await snapshot()
      target = await builtin.boundingBox()
      await dragTo(builtin, { x: target.x + target.width / 2, y: target.y + target.height / 2 + 12 })
      await expect(page.getByTestId('revision')).toHaveText('2')
      const movedStack = await snapshot(), builtinId = geometry.base.spec.blocks[0].id
      const builtinDelta = movedStack.base.blockPositions[builtinId].y - geometry.base.blockPositions[builtinId].y
      const customDelta = movedStack.custom.positions['custom-1'].y - geometry.custom.positions['custom-1'].y
      assert.ok(builtinDelta > 0); assert.ok(Math.abs(customDelta - builtinDelta) < 1e-10)
      assert.deepEqual(movedStack.custom.instances, geometry.custom.instances)
      assert.deepEqual(movedStack.base.records, geometry.base.records)
      await page.getByRole('button', { name: '拆开这组', exact: true }).click()
      await expect(page.getByTestId('revision')).toHaveText('3')
      await expect(card).not.toHaveAttribute('aria-label', /已拼接/)
      await page.getByRole('button', { name: '一键整理', exact: true }).click()
      await expect(page.getByTestId('revision')).toHaveText('4')
      // A record/config revision arriving during a pointer gesture cannot be overwritten.
      const origin = await card.boundingBox()
      await page.mouse.move(origin.x + origin.width / 2, origin.y + origin.height / 2)
      await page.mouse.down(); await page.mouse.move(origin.x + origin.width / 2, origin.y + origin.height / 2 + 12, { steps: 6 })
      await page.getByRole('button', { name: '外部 revision（测试）', exact: true }).dispatchEvent('click')
      const external = await snapshot()
      await page.mouse.up()
      await expect(page.getByRole('alert').filter({ hasText: 'REVISION_CONFLICT' })).toBeVisible()
      assert.deepEqual(await snapshot(), external)
      // Keep the same mounted React root while switching dirty drafts and versions.
      await page.setViewportSize(viewport)
      await navigate()
      await card.click()
      const duration = inspector.getByLabel('durationSeconds', { exact: true })
      const second = page.locator('[data-block-key="custom:custom-2"]')
      const persisted = await snapshot()
      await duration.fill('1111')
      await second.click()
      await expect(duration).toHaveValue('600')
      await inspector.getByLabel('title', { exact: true }).fill('B-only draft')
      await inspector.getByRole('button', { name: '保存参数', exact: true }).click()
      await expect(inspector.getByRole('status')).toContainText('宿主校验并保存')
      let lifecycle = await snapshot()
      assert.deepEqual(lifecycle.custom.instances[0], persisted.custom.instances[0])
      assert.equal(lifecycle.custom.instances[1].props.title, 'B-only draft')
      assert.equal(lifecycle.custom.instances[1].props.durationSeconds, 600)
      const secondCommitted = lifecycle.custom.instances[1]
      await card.click()
      await expect(duration).toHaveValue('900')
      await duration.fill('2222')
      await page.getByRole('button', { name: '切换 Schema 版本（测试）', exact: true }).click()
      await expect(page.getByTestId('harness-feedback')).toHaveText('版本已切换')
      await expect(duration).toHaveValue('120')
      await expect(duration).toHaveAttribute('max', '3600')
      assert.notEqual((await snapshot()).custom.instances[0].versionDigest, persisted.custom.instances[0].versionDigest)
      await duration.fill('90')
      await inspector.getByRole('button', { name: '保存参数', exact: true }).click()
      await expect(inspector.getByRole('status')).toContainText('宿主校验并保存')
      lifecycle = await snapshot()
      assert.equal(lifecycle.custom.instances[0].props.durationSeconds, 90)
      assert.deepEqual(lifecycle.custom.instances[1], secondCommitted)

      // Async real Adapter -> actual owner: revoke while registry validation waits.
      await duration.fill('180')
      await page.getByRole('button', { name: '暂停下次验证（测试）', exact: true }).click()
      await inspector.getByRole('button', { name: '保存参数', exact: true }).click()
      await expect(page.getByTestId('validation-waiting')).toHaveText('waiting')
      await page.getByLabel('只读（测试）', { exact: true }).check()
      await page.getByRole('button', { name: '继续验证（测试）', exact: true }).click()
      await expect(inspector.getByRole('alert')).toContainText('READ_ONLY')
      assert.deepEqual(await snapshot(), lifecycle)
      await expect(duration).toBeDisabled()
      await expect(inspector.getByRole('button', { name: '保存参数', exact: true })).toBeDisabled()
      await expect(page.getByRole('button', { name: '一键整理', exact: true })).toBeDisabled()
      // Physical drag attempts in readonly cannot publish geometry.
      await card.scrollIntoViewIfNeeded()
      box = await card.boundingBox()
      await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
      await page.mouse.down(); await page.mouse.move(box.x + box.width / 2 + dx, box.y + box.height / 2, { steps: 6 }); await page.mouse.up()
      assert.deepEqual(await snapshot(), lifecycle)
      await page.screenshot({ path: path.join(evidence, viewport.width > 600 ? 'desktop-readonly.png' : 'mobile-readonly.png'), fullPage: true })
      await page.getByLabel('只读（测试）', { exact: true }).uncheck()
      for (const [projection, label] of [['missing', '参数定义缺失'], ['invalid', '参数定义不可用'], ['valid', '参数定义有效']]) {
        await page.getByLabel('元数据投影（测试）', { exact: true }).selectOption(projection)
        await expect(card).toContainText(label)
        await expect(inspector).toContainText(label)
        await expect(inspector.getByRole('form', { name: '自定义积木参数' })).toHaveCount(projection === 'valid' ? 1 : 0)
        await expect(card).toContainText('当前不可执行')
        if (projection === 'invalid') await page.screenshot({ path: path.join(evidence, viewport.width > 600 ? 'desktop-invalid-schema.png' : 'mobile-invalid-schema.png'), fullPage: true })
        assert.deepEqual(await snapshot(), lifecycle)
      }
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false)
      results.push({ viewport, checks: ['selection', 'draft-no-write', 'typed-enums', 'nested-optional-props', 'trusted-schema-rejection', 'stale-draft', 'pointer-drag', 'pointer-cancel', 'isolated-instance-props', 'mixed-render-order', 'exact-version-viewer', 'pending-build', 'unavailable', 'forged-runnable-denied', 'reload-persistence', 'no-horizontal-overflow', 'collision-no-write', 'mixed-snap', 'whole-stack-single-revision', 'detach-single-revision', 'arrange-single-revision', 'stale-drag-denied', 'dirty-instance-switch', 'dirty-version-switch', 'new-version-valid-save', 'pending-readonly-owner-rejection', 'readonly-controls', 'readonly-pointer-no-write', 'shared-metadata-states'], revision: lifecycle.revision, geometryRevision: external.revision })
      await context.close()
    }
    assert.deepEqual(errors, []); assert.deepEqual(assetErrors, []); assert.deepEqual(externalRequests, [])
    const report = { scope: 'Offline static metadata only; real React lifecycle and owner; unavailable metadata uses explicit test projections; no generated component compilation or execution; no production wiring', evidence, results, errors, assetErrors, externalRequests }
    await writeFile(path.join(evidence, 'browser-report.json'), JSON.stringify(report, null, 2) + '\n')
    process.stdout.write(JSON.stringify(report, null, 2) + '\n')
  } finally { await browser?.close(); await vite.close() }
}
run().catch(error => { console.error(error); process.exitCode = 1 })
